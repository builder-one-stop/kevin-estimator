import { chromium, expect } from '@playwright/test'
import { mkdir, writeFile } from 'node:fs/promises'
import { startHarness } from './ai-local-harness.mjs'
import { PaintProvider } from '../tests/ai/paintProvider.js'
import { calculateEstimate } from '../src/lib/estimateDocument.js'
import { researchCatalog } from '../shared/researchCatalog.js'

const h = await startHarness({ provider: new PaintProvider() })
const out = 'evidence/paint-job'
await mkdir(out,{recursive:true})
const browser = await chromium.launch({channel:'chrome',headless:true})
const page = await browser.newPage({viewport:{width:1440,height:1000},acceptDownloads:true})
const report = { environment:'Local Chrome, migrated ephemeral PGlite, controlled single-room AI fixture; no live supplier or real AI', checks:[], errors:[] }
page.on('pageerror', error=>report.errors.push(error.message))
const check = value => { report.checks.push(value);console.info(value) }
const item = (doc,key) => doc.sections[0].items.find(x=>x.ruleKey===key)
try {
  await page.goto(h.url+'/__fixture/session')
  await page.getByRole('button',{name:'Enter test workspace'}).click()
  await page.getByRole('button',{name:'New conversation',exact:true}).click()
  await page.waitForURL(/\/chat\/[0-9a-f-]+$/)
  const chatUrl=page.url()
  await page.getByRole('textbox',{name:'Describe the work or request a change'}).fill('Paint only the walls of a 12 × 10 × 8 ft bedroom. Use gross walls and two coats. Patch minor nail holes.')
  await page.getByRole('button',{name:'Send',exact:true}).click()
  await expect(page.getByRole('button',{name:'Approve this revision'})).toBeEnabled({timeout:20000})
  await page.getByRole('button',{name:'Approve this revision'}).click()
  await page.getByRole('button',{name:'Generate estimate',exact:true}).click()
  await expect(page.getByTestId('complete-estimate')).toBeVisible({timeout:20000})
  const row=await h.repo.get(h.user,chatUrl.split('/').at(-1))
  const saved=()=>h.repo.estimate(h.user,row.estimate_id)
  const first=await saved()
  expect(first.document.rules.paint['bedroom-walls']).toMatchObject({areaSqFt:352,template:{coats:2}})
  expect(item(first.document,'painting:material')).toMatchObject({quantity:3,unitCost:46.98,price:{status:'public_observed',verifiedZip:null}})
  expect(first.document.sections[0].items.filter(x=>x.ruleKey.endsWith(':labor'))).toHaveLength(5)
  check('Chat approval creates 352 sf gross walls, two coats, three whole paint packages and five separate labor phases from saved rules')
  await page.getByRole('button',{name:'Edit document',exact:true}).click()
  await page.locator('.paint-rule-editor summary').click()
  await expect(page.locator('.paint-rule-editor')).toContainText('352 sf')
  await page.screenshot({path:out+'/desktop.png',fullPage:true})
  await page.getByRole('button',{name:'Review document',exact:true}).click()
  await expect(page.getByTestId('complete-estimate')).toContainText('public online price; branch/ZIP unverified')
  await page.getByRole('link',{name:'Open estimate',exact:true}).click()
  await page.locator('.estimate-tabs button').nth(1).click()
  await expect(page.locator('.ai-proposal')).toContainText('public online price; branch/ZIP unverified')
  const download=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download PDF',exact:true}).last().click()
  await (await download).saveAs(out+'/proposal-initial.pdf')
  await writeFile(out+'/saved-initial.json',JSON.stringify(first,null,2))
  report.initialTotals=calculateEstimate(first.document,first.markup_bps)
  check('Saved estimate, proposal and downloaded PDF use the same initial line quantities and totals')
  await page.reload()
  await page.locator('.estimate-tabs button').first().click()
  await page.getByLabel('Item details',{exact:true}).nth(6).click()
  const product=page.getByRole('combobox',{name:'Catalog product and price'})
  await product.selectOption(researchCatalog.find(x=>x.sourceId==='LO01').id)
  await expect(page.getByLabel('Unit',{exact:true}).nth(6)).toHaveValue('ea')
  await product.selectOption(researchCatalog.find(x=>x.sourceId==='HD01').id)
  await expect(page.getByLabel('Unit',{exact:true}).nth(6)).toHaveValue('gal')
  await expect(page.locator('.estimate-save')).toHaveText('Saved',{timeout:10000})
  check('In-chat product switch updates package unit and price source, then restores the chosen one-gallon product')
  await page.locator('.paint-rule-editor summary').click()
  await page.locator('.paint-rule-editor').getByLabel('Waste (%)').fill('20')
  await page.locator('.paint-rule-editor').getByRole('button',{name:'Recalculate painting'}).click()
  await expect(page.locator('.estimate-save')).toHaveText('Saved',{timeout:10000})
  await page.getByLabel('Unit cost',{exact:true}).nth(6).fill('49')
  await page.getByLabel('Qty',{exact:true}).nth(6).fill('4')
  await expect(page.locator('.estimate-save')).toHaveText('Saved',{timeout:10000})
  const manual=await saved()
  expect(item(manual.document,'painting:material')).toMatchObject({unitCost:49,quantity:4,price:{status:'manual'}})
  await page.locator('.paint-rule-editor').getByLabel('Length (ft)').fill('13')
  await page.locator('.paint-rule-editor').getByRole('button',{name:'Recalculate painting'}).click()
  await expect(page.locator('.estimate-save')).toHaveText('Saved',{timeout:10000})
  const revised=await saved()
  expect(revised.document.rules.paint['bedroom-walls'].areaSqFt).toBe(368)
  expect(item(revised.document,'painting:material')).toMatchObject({quantity:4,unitCost:49,price:{status:'manual'}})
  expect(item(revised.document,'protection:material').quantity).toBe(368)
  check('Reload, new dimensions and repeated recalculation retain manually overridden paint price and quantity while other phases update')
  await page.locator('.estimate-tabs button').nth(1).click()
  const language=page.getByRole('combobox',{name:'Document language',exact:true}).first()
  await language.selectOption('es')
  await expect(page.locator('.estimate-save')).toHaveText('Saved',{timeout:10000})
  await expect(page.locator('.ai-proposal')).toContainText('Entrada manual')
  const spanish=page.waitForEvent('download')
  await page.getByRole('button',{name:'Download PDF',exact:true}).last().click()
  await (await spanish).saveAs(out+'/propuesta-revisada-es.pdf')
  await writeFile(out+'/saved-revised.json',JSON.stringify(await saved(),null,2))
  report.revisedTotals=calculateEstimate(revised.document,revised.markup_bps)
  check('Spanish proposal and downloaded PDF retain revised manual values')
  await page.goto(chatUrl)
  await page.getByRole('combobox',{name:'Interface language',exact:true}).selectOption('es')
  await page.setViewportSize({width:390,height:844})
  await expect(page.getByTestId('complete-estimate')).toBeVisible()
  await expect.poll(()=>page.locator('.sidebar').evaluate(element=>element.getBoundingClientRect().right)).toBeLessThanOrEqual(0)
  await page.getByTestId('complete-estimate').locator('header').first().scrollIntoViewIfNeeded()
  report.phoneWidth=await page.evaluate(()=>({window:innerWidth,document:document.documentElement.scrollWidth}))
  expect(report.phoneWidth.document).toBeLessThanOrEqual(report.phoneWidth.window)
  await page.screenshot({path:out+'/phone.png'})
  check('390px phone view stays within the viewport after reload, in Spanish')
  await page.getByRole('combobox',{name:'Idioma de la interfaz',exact:true}).selectOption('en')
  await page.getByRole('textbox',{name:'Describe the work or request a change'}).fill('Change the paint quantity')
  await page.getByRole('button',{name:'Send',exact:true}).click()
  const cancel=page.getByRole('button',{name:'Cancel run',exact:true})
  if(await cancel.isVisible())await cancel.click()
  await expect(page.getByTestId('complete-estimate')).toBeVisible()
  expect(item((await saved()).document,'painting:material')).toMatchObject({quantity:4,unitCost:49,price:{status:'manual'}})
  check('Interrupted chat change leaves the saved manual painting estimate intact')
  expect(report.errors).toEqual([])
} catch(error) {
  report.failure=error.message;console.error(error);process.exitCode=1
  await page.screenshot({path:out+'/failure.png',fullPage:true}).catch(()=>{})
} finally {
  await writeFile(out+'/report.json',JSON.stringify(report,null,2))
  await browser.close();await h.close()
}

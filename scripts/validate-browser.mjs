import { chromium, expect } from '@playwright/test'
import { writeFileSync } from 'node:fs'
import { withFixture } from './browser-fixture.mjs'
const evidence = 'evidence/browser-validation'
const results = []
let step = 'startup'
const pass = (message) => { results.push({result:'PASS',step:message}); console.log(`PASS: ${message}`) }
const base = 'http://127.0.0.1:5173'
await withFixture(async ({tag, actionLink}) => {
 const browser = await chromium.launch({channel:'chrome',headless:process.env.BROWSER_HEADED !== '1'})
 const pageErrors = []
 const context = await browser.newContext({viewport:{width:1440,height:1000}})
 context.on('page', p => p.on('pageerror', error => pageErrors.push(error.message)))
 const page = await context.newPage()
 const save = (p) => expect(p.locator('.estimate-save')).toHaveText('Saved',{timeout:15000})
 const screenshot = (p,name) => p.screenshot({path:`${evidence}/${name}.png`,fullPage:true})
 const abortWrites = route => route.request().method()==='PATCH' ? route.abort('failed') : route.continue()
 try {
  step='magic-link sign-in'
  try { await page.goto(actionLink) } catch { throw new Error('Magic-link navigation failed (URL withheld)') }
  await expect(page.getByRole('heading',{name:'Recent estimates'})).toBeVisible({timeout:20000})
  pass('Real Chrome + Supabase magic-link callback authenticates; email delivery is not tested by generated link')
  step='contact creation'
  await page.getByRole('link',{name:'Contacts',exact:true}).click()
  await page.getByRole('button',{name:'Add contact',exact:true}).first().click()
  await page.getByRole('dialog').getByLabel('Name').fill(`${tag} Contact`)
  await page.getByRole('dialog').getByLabel('Address').fill('TEST ONLY — no real address')
  await page.getByRole('button',{name:'Save contact',exact:true}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText(`${tag} Contact`,{exact:true})).toBeVisible()
  pass('Created a contact through UI and real Supabase')
  step='linked project creation'
  await page.getByRole('link',{name:'Projects',exact:true}).click()
  await page.getByRole('button',{name:'Create project',exact:true}).first().click()
  await page.getByRole('dialog').getByLabel('Project name').fill(`${tag} Project`)
  await page.getByRole('dialog').getByRole('combobox',{name:/^Client/}).selectOption({label:`${tag} Contact`})
  await page.getByRole('dialog').getByRole('button',{name:'Save project'}).click()
  await expect(page.getByRole('dialog')).toHaveCount(0)
  await expect(page.getByText(`${tag} Project`,{exact:true})).toBeVisible()
  pass('Created project linked to the test contact through UI')
  await screenshot(page,'03-linked-project')
  step='dashboard estimate creation'
  await page.getByRole('link',{name:'Home',exact:true}).click()
  await page.locator('.home').getByRole('button',{name:'New estimate',exact:true}).click()
  await page.getByLabel('Estimate name',{exact:true}).fill(`${tag} Dashboard`)
  await page.getByRole('combobox',{name:/^Project/}).selectOption({label:`${tag} Project`})
  await expect(page.getByRole('combobox',{name:/^Client/}).locator('option:checked')).toHaveText(`${tag} Contact`)
  await page.getByRole('button',{name:'Add section',exact:true}).click()
  await page.getByLabel('Section name',{exact:true}).fill('Test kitchen')
  await page.getByRole('button',{name:'Add item',exact:true}).click()
  await page.getByLabel('Description',{exact:true}).fill('Test cabinets')
  await page.getByLabel('Qty',{exact:true}).fill('2')
  await page.getByLabel('Unit cost',{exact:true}).fill('100')
  await expect(page.locator('.estimate-save')).toHaveText('Saving…')
  await save(page)
  await expect(page.locator('.grand')).toContainText('$272.00')
  await page.getByLabel('Qty',{exact:true}).fill('2.5')
  await page.getByLabel('Unit cost',{exact:true}).fill('120.50')
  await save(page)
  await expect(page.locator('.grand')).toContainText('$409.70')
  pass('Dashboard estimate: inherited client; edited quantity/prices; 2×100→272 and 2.5×120.50→409.70 at 36% markup; Saving/Saved observed')
  const estimatePath = new URL(page.url()).pathname
  await screenshot(page,'04-estimate-saved')
  step='reload and reopen'
  await page.reload()
  await expect(page.getByLabel('Qty',{exact:true})).toHaveValue('2.5')
  await expect(page.locator('.grand')).toContainText('$409.70')
  await page.locator('.sidebar').getByRole('link',{name:'Estimates',exact:true}).click()
  await page.getByRole('link',{name:`${tag} Dashboard`,exact:true}).click()
  await expect(page.getByLabel('Unit cost',{exact:true})).toHaveValue('120.50')
  pass('Reloaded and reopened the persisted estimate with correct item values and totals')
  step='navigation estimate creation'
  await page.locator('.sidebar').getByRole('link',{name:'Estimates',exact:true}).click()
  await page.locator('.page-head').getByRole('button',{name:'New estimate'}).click()
  await page.getByLabel('Estimate name',{exact:true}).fill(`${tag} Navigation`)
  await save(page)
  pass('Created a second estimate from Estimates navigation')
  step='two-tab conflict'
  await page.goto(base+estimatePath)
  await page.getByLabel('Description',{exact:true}).waitFor()
  const second = await context.newPage()
  await second.goto(base+estimatePath)
  await second.getByLabel('Description',{exact:true}).waitFor()
  await second.route('**/rest/v1/estimates*',abortWrites)
  await second.getByLabel('Description',{exact:true}).fill('TAB B pending work')
  await expect(second.locator('.estimate-save')).toHaveText('Save failed',{timeout:10000})
  await page.getByLabel('Description',{exact:true}).fill('TAB A saved work')
  await save(page)
  await expect(second.getByLabel('Description',{exact:true})).toHaveValue('TAB B pending work')
  await second.unroute('**/rest/v1/estimates*',abortWrites)
  await second.getByRole('button',{name:'Retry save',exact:true}).click()
  await expect(second.getByRole('button',{name:'Save my draft',exact:true})).toBeVisible()
  await screenshot(second,'05-conflict-two-tabs')
  await second.reload()
  await expect(second.getByLabel('Description',{exact:true})).toHaveValue('TAB B pending work')
  await expect(second.getByRole('button',{name:'Save my draft',exact:true})).toBeVisible()
  await second.getByRole('button',{name:'Save my draft',exact:true}).click()
  await save(second)
  await page.reload()
  await expect(page.getByLabel('Description',{exact:true})).toHaveValue('TAB B pending work')
  pass('Two real tabs: failed B draft survives A save and reload; stale retry shows conflict; explicit Save my draft persists B')
  step='discard only selected draft'
  await second.route('**/rest/v1/estimates*',abortWrites)
  await second.getByLabel('Description',{exact:true}).fill('TAB B discard explicitly')
  await expect(second.locator('.estimate-save')).toHaveText('Save failed',{timeout:10000})
  await page.getByLabel('Description',{exact:true}).fill('TAB A next saved version')
  await save(page)
  await second.unroute('**/rest/v1/estimates*',abortWrites)
  await second.getByRole('button',{name:'Retry save',exact:true}).click()
  await expect(second.getByRole('button',{name:'Use remote version',exact:true})).toBeVisible()
  await page.route('**/rest/v1/estimates*',abortWrites)
  await page.getByLabel('Description',{exact:true}).fill('TAB A independent pending draft')
  await expect(page.locator('.estimate-save')).toHaveText('Save failed',{timeout:10000})
  await second.getByRole('button',{name:'Use remote version',exact:true}).click()
  await expect(second.getByLabel('Description',{exact:true})).toHaveValue('TAB A next saved version')
  await second.getByRole('button',{name:`Recover: ${tag} Dashboard`,exact:true}).click()
  await expect(second.getByLabel('Description',{exact:true})).toHaveValue('TAB A independent pending draft')
  await second.getByRole('button',{name:'Save my draft',exact:true}).click()
  await save(second)
  await page.unroute('**/rest/v1/estimates*',abortWrites)
  await page.reload()
  await expect(page.getByLabel('Description',{exact:true})).toHaveValue('TAB A independent pending draft')
  pass('Use remote discards only selected B draft; A’s independent pending revision remains recoverable and saves correctly')
  step='pending changes across language switch'
  await second.route('**/rest/v1/estimates*',abortWrites)
  await second.getByLabel('Description',{exact:true}).fill('PENDIENTE bilingüe')
  await expect(second.locator('.estimate-save')).toHaveText('Save failed',{timeout:10000})
  await second.locator('button.company').click()
  await second.getByRole('menuitem',{name:'Settings'}).click()
  await second.getByRole('button',{name:'Español',exact:true}).click()
  await second.locator('.sidebar').getByRole('link',{name:'Estimados',exact:true}).click()
  await second.getByRole('link',{name:`${tag} Dashboard`,exact:true}).click()
  await expect(second.getByLabel('Descripción',{exact:true})).toHaveValue('PENDIENTE bilingüe')
  await expect(second.locator('.estimate-save')).toHaveText('Error al guardar',{timeout:10000})
  await screenshot(second,'06-spanish-pending')
  await second.unroute('**/rest/v1/estimates*',abortWrites)
  await second.getByRole('button',{name:'Reintentar guardado',exact:true}).click()
  await expect(second.locator('.estimate-save')).toHaveText('Guardado',{timeout:15000})
  pass('Changed EN→ES through Settings with failed pending edits; reopened draft retained input, Spanish errors, then saved')
  step='load error and retry'
  const failLoad = route => route.request().method()==='GET' ? route.fulfill({status:503,contentType:'application/json',body:JSON.stringify({message:'Controlled QA failure'})}) : route.continue()
  await second.route('**/rest/v1/estimates*',failLoad)
  await second.reload()
  await expect(second.getByRole('status')).toContainText('Cargando')
  pass('Real browser displays loading while Supabase requests retry')
  await expect(second.getByRole('alert')).toContainText('No se pudo cargar',{timeout:30000})
  await screenshot(second,'07-load-error')
  await second.unroute('**/rest/v1/estimates*',failLoad)
  await second.getByRole('button',{name:'Intentar de nuevo',exact:true}).click()
  await expect(second.getByLabel('Descripción',{exact:true})).toHaveValue('PENDIENTE bilingüe')
  pass('Controlled real-browser load failure displays Spanish error; retry reloads real Supabase data')
  step='sign out'
  await second.locator('button.company').click()
  await second.getByRole('menuitem',{name:'Cerrar sesión',exact:true}).click()
  await expect(second.getByRole('heading',{name:'Inicia sesión en One Stop'})).toBeVisible({timeout:15000})
  await expect(page.getByRole('heading',{name:'Sign in to One Stop'})).toBeVisible({timeout:15000})
  await second.reload()
  await expect(second.getByRole('heading',{name:'Inicia sesión en One Stop'})).toBeVisible()
  pass('Sign-out through UI removes private content in both tabs and survives reload')
  await screenshot(second,'08-signed-out')
  expect(pageErrors).toEqual([])
  pass('No uncaught browser application errors during the integrated journey')
 } catch(error) {
   results.push({result:'FAIL',step,message:error.message.replace(/https?:\/\/[^\s]+/g,'[URL withheld]').slice(0,1600)})
   console.log(`FAIL at ${step}: ${results.at(-1).message}`)
   await screenshot(page,'failure-current-page')
   process.exitCode=1
 } finally {
   writeFileSync(`${evidence}/results.json`,JSON.stringify({browser:'Google Chrome',backend:'vtpciccluvpaclbeqxih',results},null,2)+'\n')
   await browser.close()
 }
})
